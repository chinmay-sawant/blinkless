package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"os"
	"reflect"
	"strconv"
	"strings"
)

// styleGroup is a lazily stored group of related ResolvedStyle fields.
// Ordinary pointer payloads are handled separately by classifyPtr.
type styleGroup struct {
	field    string
	accessor string
	typeName string
}

func (g styleGroup) stem() string { return strings.ToUpper(g.accessor[:1]) + g.accessor[1:] }

func fieldTag(field *ast.Field, name string) string {
	if field.Tag == nil {
		return ""
	}

	tag, _ := strconv.Unquote(field.Tag.Value)

	return reflect.StructTag(tag).Get(name)
}

func parseStyleGroups(target *ast.StructType) ([]styleGroup, error) {
	groups := make([]styleGroup, 0)

	for _, field := range target.Fields.List {
		accessor := fieldTag(field, "stylegroup")
		if accessor == "" {
			continue
		}

		pointer, isPointer := field.Type.(*ast.StarExpr)
		if !isPointer || len(field.Names) != 1 {
			return nil, fmt.Errorf("%w: named style group's field must be a named pointer", errUnsupported)
		}
		if _, ok := pointer.X.(*ast.Ident); !ok {
			return nil, fmt.Errorf("%w: style group's pointer must refer to a package struct", errUnsupported)
		}

		groups = append(groups, styleGroupFrom(field, accessor))
	}

	return groups, nil
}

func styleGroupFrom(field *ast.Field, accessor string) styleGroup {
	return styleGroup{
		field:    field.Names[0].Name,
		accessor: accessor,
		typeName: field.Type.(*ast.StarExpr).X.(*ast.Ident).Name,
	}
}

func (g *generator) checkStyleGroup(group styleGroup) error {
	st, ok := g.structs[group.typeName]
	if !ok {
		return fmt.Errorf("%w: style group %s", errNotFound, group.typeName)
	}

	_, _, _, err := g.fields("a", "b", "s", st)

	return err
}

func (g *generator) writeStyleGroupStorage(path string) error {
	if len(g.groups) == 0 {
		return nil
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/gen-style-intern; DO NOT EDIT.\n\npackage layout\n\nimport \"sync\"\n\n")
	buf.WriteString(`// styleGroupBuilder owns the mutable copies used only during one cascade.
// Resolved and interned styles never retain a reference to it.
type styleGroupBuilder struct {
`)
	for _, group := range g.groups {
		fmt.Fprintf(&buf, "\t%s %s\n", group.accessor, group.typeName)
	}
	buf.WriteString(`}

var styleGroupBuilders = sync.Pool{New: func() any { return new(styleGroupBuilder) }}

func (s *ResolvedStyle) beginStyleGroups() {
	s.groups = styleGroupBuilders.Get().(*styleGroupBuilder)
}

func (s *ResolvedStyle) finishStyleGroups() {
	builder := s.groups
	s.groups = nil
`)
	for _, group := range g.groups {
		stem := group.stem()
		fmt.Fprintf(&buf, `	if s.%[1]s == &builder.%[2]s {
		s.%[1]s = freezeStyleGroup(s.%[1]s, &initialStyle%[3]s, styleInternEqual%[3]s)
	}
`, group.field, group.accessor, stem)
	}
	buf.WriteString(`	*builder = styleGroupBuilder{}
	styleGroupBuilders.Put(builder)
}

func freezeStyleGroup[T any](value, initial *T, equal func(*T, *T) bool) *T {
	if equal(value, initial) {
		return initial
	}
	if equal(value, nil) {
		return nil
	}

	copy := *value

	return &copy
}

`)
	for _, group := range g.groups {
		renderStyleGroupAccessors(&buf, group)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt generated style group storage: %w", err)
	}
	if err := os.WriteFile(path, formatted, generatedFilePerm); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func (g *generator) renderStyleGroups(buf *bytes.Buffer) error {
	if len(g.groups) == 0 {
		return nil
	}

	fieldLists := make([][]string, 0, len(g.groups))
	for _, group := range g.groups {
		eqTerms, hashLines, fieldNames, err := g.fields("a", "b", "s", g.structs[group.typeName])
		if err != nil {
			return err
		}

		renderStyleGroup(buf, group, eqTerms, hashLines)
		fieldLists = append(fieldLists, fieldNames)
	}

	buf.WriteString("func styleInternGroupFields() map[string][]string {\nreturn map[string][]string{\n")
	for i, group := range g.groups {
		fmt.Fprintf(buf, "%q: strings.Fields(%q),\n", group.field, strings.Join(fieldLists[i], " "))
	}
	buf.WriteString("}\n}\n")

	return nil
}

func renderStyleGroup(buf *bytes.Buffer, g styleGroup, eqTerms, hashLines []string) {
	fmt.Fprintf(buf, `var zeroStyle%[3]s %[4]s
var zeroStyle%[3]sHash = computeStyleHash%[3]s(&zeroStyle%[3]s)
var initialStyle%[3]sHash = computeStyleHash%[3]s(&initialStyle%[3]s)

func styleInternEqual%[3]s(a, b *%[4]s) bool {
	if a == b && (a == nil || a == &initialStyle%[3]s) {
		return true
	}
	if a == nil {
		a = &zeroStyle%[3]s
	}
	if b == nil {
		b = &zeroStyle%[3]s
	}

	return `, g.field, g.accessor, g.stem(), g.typeName)
	buf.WriteString(strings.Join(eqTerms, " &&\n\t\t"))
	buf.WriteString("\n}\n\n")
	fmt.Fprintf(buf, `func styleInternHash%[1]s(s *%[2]s) uint64 {
	switch s {
	case nil:
		return zeroStyle%[1]sHash
	case &initialStyle%[1]s:
		return initialStyle%[1]sHash
	default:
		return computeStyleHash%[1]s(s)
	}
}

func computeStyleHash%[1]s(s *%[2]s) uint64 {
	h := styleInternSeed
`, g.stem(), g.typeName)
	for _, line := range hashLines {
		buf.WriteString("\t" + line + "\n")
	}
	buf.WriteString("\n\treturn h\n}\n\n")
}

func renderStyleGroupAccessors(buf *bytes.Buffer, g styleGroup) {
	fmt.Fprintf(buf, `// %[2]s returns the group's values for reading.
func (s *ResolvedStyle) %[2]s() *%[4]s {
	if s.%[1]s != nil {
		return s.%[1]s
	}

	return &zeroStyle%[3]s
}

func (s *ResolvedStyle) edit%[3]s() *%[4]s {
	if b := s.groups; b != nil {
		if s.%[1]s != &b.%[2]s {
			b.%[2]s = *s.%[2]s()
			s.%[1]s = &b.%[2]s
		}

		return s.%[1]s
	}

	copy := *s.%[2]s()
	s.%[1]s = &copy

	return &copy
}

`, g.field, g.accessor, g.stem(), g.typeName)
}
